/**
 * Gera lib/municipios-br.ts com todos os 5.570 municípios brasileiros.
 *
 * Fonte: IBGE API — Localidades
 * https://servicodados.ibge.gov.br/api/v1/localidades/municipios
 *
 * Execute: node scripts/generate-municipios.mjs
 */

import { writeFileSync } from "fs"
import { join, dirname } from "path"
import { fileURLToPath } from "url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUTPUT    = join(__dirname, "../lib/municipios-br.ts")
const IBGE_URL  = "https://servicodados.ibge.gov.br/api/v1/localidades/municipios?orderBy=nome"

console.log("⬇  Buscando municípios no IBGE...")

const res  = await fetch(IBGE_URL)
const data = await res.json()

console.log(`✓  ${data.length} municípios recebidos`)

// Extrai apenas nome + sigla do estado.
// Fallback para regiao-imediata nos (raros) municípios sem microrregiao.
const municipios = data.map((m) => ({
  nome: m.nome,
  uf:   m.microrregiao?.mesorregiao?.UF?.sigla
     ?? m["regiao-imediata"]?.["regiao-intermediaria"]?.UF?.sigla
     ?? "BR",
}))

// Gera o arquivo TypeScript
const lines = municipios.map(
  ({ nome, uf }) => `  { nome: ${JSON.stringify(nome)}, uf: ${JSON.stringify(uf)} },`
)

const output = `\
// AUTO-GENERATED by scripts/generate-municipios.mjs — não editar manualmente.
// Fonte: IBGE API — Localidades (CC BY 4.0)
// Municípios: ${municipios.length} total, ordenados por nome

export interface Municipio {
  nome: string
  uf:   string
}

export const MUNICIPIOS: readonly Municipio[] = [
${lines.join("\n")}
]
`

writeFileSync(OUTPUT, output, "utf-8")
console.log(`✓  Arquivo gerado: lib/municipios-br.ts (${municipios.length} municípios)`)
